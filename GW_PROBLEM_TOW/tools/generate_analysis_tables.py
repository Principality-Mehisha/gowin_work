def font_rows():
    data=[0]*1024
    for char,rows in FONT.items():
        for row,bits in enumerate(rows.split()): data[ord(char)*8+row]=int(bits,2)
    return data


def tables():
    window = [round(32767 * (0.5 - 0.5 * math.cos(2*math.pi*n/1023))) for n in range(1024)]
    twiddle = [((round(32767*math.cos(2*math.pi*k/1024)) & 65535) << 16) |
               (round(-32767*math.sin(2*math.pi*k/1024)) & 65535) for k in range(512)]
    return window, twiddle


if __name__ == '__main__':
    for name, data, width in zip(('analysis_window.hex', 'analysis_twiddle.hex', 'analysis_font.hex'), (*tables(),font_rows()), (4, 8, 2)):
        path = ROOT/'src/video'/name
        content = ''.join(f'{n:0{width}x}\n' for n in data)
        if '--check' in sys.argv:
            assert path.read_text() == content, f'Stale table: {path}'
        else:
            path.write_text(content, encoding='ascii')
