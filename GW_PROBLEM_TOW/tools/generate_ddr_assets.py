"""Pack the three clarinet layers into 128-bit DDR bursts; no block-RAM seed.

The boot source is explicitly distributed ROM. Runtime tables are read from
DDR, and every initialized burst is read back before the service becomes ready.
"""
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]


def main():
    voice = [int(x, 16) for x in (ROOT/'src/rom/clarinet45.hex').read_text().split()]
    env = [int(x, 16) for x in (ROOT/'src/rom/clarinet45_env.hex').read_text().split()]
    assert len(voice) == 4320 and len(env) == 135
    words = [sum(voice[(layer*45+note)*32+h] << (40*layer) for layer in range(3))
             for note in range(45) for h in range(32)] + env
    lines = ['// Generated by tools/generate_ddr_assets.py; do not edit.',
             '// Burst 0..1439: {8b0, ff40, mf40, pp40}; 1440..1574: envelope96.',
             '// Two pipeline stages keep the wide LUT ROM off a single UI path.',
             'module ddr_asset_seed(input wire clk, input wire [10:0] address,',
             ' output reg [127:0] data);', ' reg [3:0] page_select;',
             ' always @(posedge clk) page_select<=address[10:7];']
    pages = (len(words)+127)//128
    for page in range(pages):
        lines += [f' reg [127:0] page{page} /* synthesis syn_romstyle="distributed_rom" */;',
                  ' always @(posedge clk) begin', '  case(address[6:0])']
        lines += [f"   7'd{i}: page{page}<=128'h{word:032x};"
                  for i, word in enumerate(words[page*128:(page+1)*128])]
        lines += [f"   default: page{page}<=128'd0;", '  endcase', ' end']
    lines += [' always @(posedge clk) begin', '  case(page_select)']
    lines += [f"   4'd{page}: data<=page{page};" for page in range(pages)]
    lines += ["   default: data<=128'd0;", '  endcase', ' end', 'endmodule', '']
    outputs = {ROOT/'src/ddr/ddr_asset_seed.v': '\n'.join(lines),
               ROOT/'sim/ddr_assets.hex': ''.join(f'{x:032x}\n' for x in words)}
    for path, content in outputs.items():
        if '--check' in sys.argv:
            assert path.read_text(encoding='ascii') == content, f'Stale DDR asset: {path}'
        else:
            path.write_text(content, encoding='ascii')
    print(f'PASS: {len(words)} DDR bursts match all clarinet parameters ({len(words)*16} bytes)')


if __name__ == '__main__':
    main()
