"""Compile the deployed PIANO.BIN into a compact display look-ahead ROM."""
from pathlib import Path
import hashlib
import json
import sys
from score_bin import read_p88s

ROOT = Path(__file__).resolve().parents[1]

def main():
    source = ROOT / 'sd_card/PIANO.BIN'
    events, info = read_p88s(source)
    assert len(events) <= 4095
    assert max(t + d for t, d, _ in events) < 16384, 'Display score exceeds 273 seconds'
    assert max(d for t, d, _ in events) < 2048, 'Display note exceeds 34 seconds'
    durations=sorted({d for t,d,n in events})
    assert len(durations)<=8, 'Display ROM supports eight distinct note durations'
    changes={}
    for start,duration,note in events:
        changes[start-180]=changes.get(start-180,0)+1
        changes[start+duration]=changes.get(start+duration,0)-1
    slots=peak=0
    for time,delta in sorted(changes.items()):
        slots+=delta
        peak=max(peak,slots)
    assert peak<=64, f'Display requires {peak} simultaneous notes, capacity is 64'
    # 24 bits: start14, duration dictionary index3, pitch7. Three BSRAMs.
    depth = 1 << (len(events)-1).bit_length()
    lines = ['// Generated by tools/generate_video_score.py from sd_card/PIANO.BIN.',
             f'// SHA256 {info["sha256"]}',
             'module piano_score_rom(input wire clk, input wire [11:0] address,',
             ' output wire [31:0] data, output wire [11:0] count);',
             f' assign count = 12\'d{len(events)};',
             ' reg [23:0] packed_note;', ' reg [10:0] duration;',
             ' assign data={packed_note[23:10],duration,packed_note[6:0]};',
             ' always @* begin', '  case(packed_note[9:7])']
    lines += [f"   3'd{i}: duration=11'd{d};" for i,d in enumerate(durations)]
    lines += ["   default: duration=0;", '  endcase', ' end',
              f' reg [23:0] contents [0:{depth-1}];', ' initial begin']
    for i in range(depth):
        word = (16383 << 10) if i >= len(events) else ((events[i][0] << 10) | (durations.index(events[i][1]) << 7) | events[i][2])
        lines.append(f"  contents[{i}] = 24'h{word:06x};")
    lines += [' end', f' always @(posedge clk) packed_note <= contents[address[{(depth-1).bit_length()-1}:0]];', 'endmodule', '']
    target = ROOT/'src/video/piano_score_rom.v'
    content = '\n'.join(lines)
    if '--check' in sys.argv:
        assert target.read_text(encoding='ascii') == content, 'Display ROM differs from sd_card/PIANO.BIN; run tools/generate_video_score.py'
        saved=json.loads((ROOT/'src/video/score_metadata.json').read_text())
        assert saved['sha256']==info['sha256'], 'Stale video source fingerprint'
        assert saved['rom_sha256']==hashlib.sha256(target.read_bytes()).hexdigest(), 'Stale video ROM fingerprint'
        print('PASS: display ROM exactly matches deployed piano score')
        return
    target.write_text(content, encoding='ascii')
    metadata = {k:v for k,v in info.items() if k not in ('notes','path')}
    metadata['rom_sha256'] = hashlib.sha256(target.read_bytes()).hexdigest()
    (ROOT/'src/video/score_metadata.json').write_text(json.dumps(metadata, indent=2)+'\n', encoding='ascii')
    print(f'PASS: display ROM compiled from {len(events)} piano notes')

if __name__ == '__main__':
    main()
