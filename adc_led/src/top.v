//======================================================================
//  Tang Mega 60K on-chip ADC to binary LED display
//
//  ADCV is a dedicated analogue differential input of the GW5AT-60:
//    ADCVP = L10  (external 0..1 V signal)
//    ADCVN = M9   (analogue ground / signal return)
//
//  The dedicated ADC balls are consumed directly by the ADC_SAR hard macro
//  and therefore do not appear as top-level ports or ordinary CST IO_LOCs.
//======================================================================
`timescale 1ns / 1ps

module top #(
    // Delay between completed conversions.  1024 clocks = 20.48 us at 50 MHz.
    parameter SAMPLE_GAP = 1024,
    // ADC clock is 50 MHz / 8 = 6.25 MHz.  Keep ADCREQI high for 16 system
    // clocks (320 ns), spanning two complete ADC clock periods.
    parameter REQUEST_CYCLES = 16,
    // Retry if ADCRDY is not seen within 100 ms.
    parameter ADC_TIMEOUT_CYCLES = 5_000_000
)(
    input        clk,
    output [7:0] led_o
);

    // Use the device configuration reset as the reset source.  This avoids
    // relying on a Verilog declaration-time initial value, which is not a
    // portable way to reset the ADC hard macro on every configuration.
    GSR GSR_INST (
        .GSRI(1'b1)
    );

    // Keep the ADC in digital reset for 2^16 system clocks (~1.31 ms), then
    // release reset synchronously to the 50 MHz fabric clock.  GSR clears
    // this shift register during configuration, so reset has a deterministic
    // low level and a real rising edge after configuration.
    (* keep = "true" *) reg [15:0] reset_pipe = 16'd0;
    always @(posedge clk) begin
        reset_pipe <= {reset_pipe[14:0], 1'b1};
    end
    wire rstn = reset_pipe[15];

    wire        adc_ready;
    wire [13:0] adc_value;
    wire [7:0]  mdrp_rdata_unused;

    reg         adc_request;
    reg [15:0]  gap_count;
    reg         adc_seen;
    reg [1:0]   adc_state;
    reg [7:0]   request_count;
    reg [22:0]  timeout_count;
    reg [1:0]   adc_ready_sync;
    reg [13:0]  adc_value_latched;
    reg         adc_sample_valid;

    localparam ADC_GAP       = 2'd0;
    localparam ADC_REQUEST   = 2'd1;
    localparam ADC_WAIT_HIGH = 2'd2;
    localparam ADC_WAIT_LOW  = 2'd3;

    // Power-on LED test: light LED0..LED7 for 125 ms each.  Afterwards LED7
    // blinks if the ADC has never completed a conversion.
    reg [22:0]  selftest_count;
    reg [3:0]   selftest_step;
    reg [24:0]  heartbeat_count;

    // ADCRDY is generated by the ADC hard macro.  Synchronize it before using
    // it in fabric logic, and use a level handshake (wait high, then wait
    // low) so both pulse-style and level-style completion indications work.
    always @(posedge clk or negedge rstn) begin
        if (!rstn)
            adc_ready_sync <= 2'b00;
        else
            adc_ready_sync <= {adc_ready_sync[0], adc_ready};
    end

    wire adc_ready_fabric = adc_ready_sync[1];
    wire adc_done_event = (adc_state == ADC_WAIT_HIGH) && adc_ready_fabric;

    // Voltage mode, ADCV channel.  The generated IP divides the 50 MHz clock
    // by 8, giving a 6.25 MHz ADC clock (inside the specified 0.5..8 MHz range).
    Gowin_ADC u_adc (
        .adcrdy       (adc_ready),
        .adcvalue     (adc_value),
        .mdrp_rdata   (mdrp_rdata_unused),
        .adcmode      (1'b1),
        .vsenctl      (3'b000),
        .clk          (clk),
        .drstn        (rstn),
        .adcreqi      (adc_request),
        .mdrp_clk     (1'b0),
        .mdrp_wdata   (8'b0),
        .mdrp_a_inc   (1'b0),
        .mdrp_opcode  (2'b00)
    );

    // Stretch ADCREQI so the divided ADC clock cannot miss it.  A timeout
    // returns to ADC_GAP and retries instead of waiting forever.  Once a
    // conversion completes, wait for ADCRDY to return low before issuing the
    // next request; this prevents a level-style ADCRDY from being mistaken
    // for an immediate completion of the next conversion.
    always @(posedge clk or negedge rstn) begin
        if (!rstn) begin
            adc_request        <= 1'b0;
            gap_count          <= SAMPLE_GAP - 1;
            adc_seen           <= 1'b0;
            adc_state          <= ADC_WAIT_LOW;
            request_count      <= 8'd0;
            timeout_count      <= 23'd0;
        end else begin
            case (adc_state)
                ADC_GAP: begin
                    adc_request <= 1'b0;
                    if (gap_count != 0) begin
                        gap_count <= gap_count - 1'b1;
                    end else begin
                        adc_request   <= 1'b1;
                        request_count <= REQUEST_CYCLES - 1;
                        adc_state     <= ADC_REQUEST;
                    end
                end

                ADC_REQUEST: begin
                    adc_request <= 1'b1;
                    if (request_count != 0) begin
                        request_count <= request_count - 1'b1;
                    end else begin
                        adc_request <= 1'b0;
                        timeout_count <= 23'd0;
                        adc_state <= ADC_WAIT_HIGH;
                    end
                end

                ADC_WAIT_HIGH: begin
                    adc_request <= 1'b0;
                    if (adc_ready_fabric) begin
                        adc_seen <= 1'b1;
                        adc_state <= ADC_WAIT_LOW;
                    end else if (timeout_count == ADC_TIMEOUT_CYCLES - 1) begin
                        timeout_count <= 23'd0;
                        gap_count <= 16'd0;
                        adc_state <= ADC_GAP;
                    end else begin
                        timeout_count <= timeout_count + 1'b1;
                    end
                end

                default: begin  // ADC_WAIT_LOW
                    adc_request <= 1'b0;
                    timeout_count <= 23'd0;
                    if (!adc_ready_fabric) begin
                        gap_count <= SAMPLE_GAP - 1;
                        adc_state <= ADC_GAP;
                    end
                end
            endcase
        end
    end

    // Capture the bus only after synchronized ADCRDY.  The valid pulse is
    // consumed by adc_led one fabric clock later, when the latched bus is
    // already stable.
    always @(posedge clk or negedge rstn) begin
        if (!rstn) begin
            adc_value_latched <= 14'd0;
            adc_sample_valid  <= 1'b0;
        end else begin
            adc_sample_valid <= 1'b0;
            if (adc_done_event) begin
                adc_value_latched <= adc_value;
                adc_sample_valid  <= 1'b1;
            end
        end
    end

    // UG299 specifies voltage = adcvalue / 2048 for this ADC.  Therefore the
    // useful 0..1 V range is code 0..2048, not the complete 14-bit range.
    // Clamp over-range results and present an 11-bit 0..2047 value to adc_led;
    // bits [10:8] then form the required eight equal voltage ranges.
    wire [10:0] adc_code_1v =
        (adc_value_latched >= 14'd2047) ? 11'd2047 : adc_value_latched[10:0];
    wire [7:0] adc_led_o;

    adc_led #(
        .ADC_BITS   (11),
        .HYST       (0),
        .ACTIVE_LOW (1)
    ) u_display (
        .clk      (clk),
        .rstn     (rstn),
        .adc_data (adc_code_1v),
        .adc_dv   (adc_sample_valid),
        .led_o    (adc_led_o)
    );

    always @(posedge clk or negedge rstn) begin
        if (!rstn) begin
            selftest_count  <= 23'd0;
            selftest_step   <= 4'd0;
            heartbeat_count <= 25'd0;
        end else begin
            heartbeat_count <= heartbeat_count + 1'b1;

            if (selftest_step < 4'd8) begin
                if (selftest_count == 23'd6_249_999) begin
                    selftest_count <= 23'd0;
                    selftest_step <= selftest_step + 1'b1;
                end else begin
                    selftest_count <= selftest_count + 1'b1;
                end
            end
        end
    end

    wire [7:0] selftest_led_o = ~(8'b0000_0001 << selftest_step[2:0]);
    wire [7:0] no_adc_led_o =
        heartbeat_count[24] ? 8'b0111_1111 : 8'b1111_1111;

    assign led_o = (selftest_step < 4'd8) ? selftest_led_o :
                   adc_seen               ? adc_led_o :
                                            no_adc_led_o;

endmodule
