"""Generate keyboard/score ROMs and independent animation reference data.

Optional --midi requires mido; default is a self-contained 88-key exercise.
"""
from __future__ import annotations
import argparse
import collections
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BLACK = {1, 3, 6, 8, 10}
KEY_Y, LEAD, SPEED, SLOTS = 720, 180, 4, 64


def keyboard():
    keys, white = [], 0
    for pitch in range(21, 109):
        black = pitch % 12 in BLACK
        center = 20 + white * 30 if black else 35 + white * 30
        width = 18 if black else 30
        keys.append(dict(note=pitch - 21, midi=pitch, black=black,
                         left=center - width // 2, right=center + width // 2,
                         center=center))
        white += not black
    assert white == 52 and sum(k['black'] for k in keys) == 36
    return keys


def demo():
    events = [(0, 48, n - 21) for n in (36, 48, 60, 64, 67, 72)]
    events += [(60 + i * 8, 24 + (i % 4) * 6, i) for i in range(88)]
    chords = [(33, 45, 57, 60, 64, 69), (38, 50, 57, 62, 65, 69),
              (31, 43, 55, 59, 62, 67), (36, 48, 60, 64, 67, 72),
              (37, 49, 61, 65, 68, 73), (42, 54, 61, 66, 69, 73)]
    for i, chord in enumerate(chords):
        events += [(820 + i * 60, 42, n - 21) for n in chord]
    return sorted(events)


def midi_events(path):
    sys.path.insert(0, str(ROOT.parent / 'Piano_88/tools/vendor'))
    import mido
    active = collections.defaultdict(collections.deque)
    sustained = collections.defaultdict(list)
    pedal = collections.defaultdict(bool)
    events, seconds = [], 0.0

    def finish(pitch, start, end):
        if 21 <= pitch <= 108:
            frame = round(start * 60)
            events.append((frame, max(2, round(end * 60) - frame), pitch - 21))

    for msg in mido.MidiFile(path):
        seconds += msg.time
        channel = getattr(msg, 'channel', 0)
        if channel == 9:
            continue
        if msg.type == 'note_on' and msg.velocity:
            active[channel, msg.note].append(seconds)
        elif msg.type == 'note_off' or msg.type == 'note_on':
            if active[channel, msg.note]:
                start = active[channel, msg.note].popleft()
                if pedal[channel]:
                    sustained[channel].append((msg.note, start))
                else:
                    finish(msg.note, start, seconds)
        elif msg.type == 'control_change' and msg.control == 64:
            pedal[channel] = msg.value >= 64
            if not pedal[channel]:
                for pitch, start in sustained.pop(channel, []):
                    finish(pitch, start, seconds)
    for (_, pitch), starts in active.items():
        for start in starts:
            finish(pitch, start, seconds)
    for notes in sustained.values():
        for pitch, start in notes:
            finish(pitch, start, seconds)
    if not events:
        raise ValueError('No A0..C8 piano notes found')
    return sorted(events)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--midi', type=Path)
    args = parser.parse_args()
    keys = keyboard()
    events = midi_events(args.midi) if args.midi else demo()
    loop = max(t + d + LEAD for t, d, _ in events) + 90
    if len(events) > 4095 or loop > 65535 or max(d for _, d, _ in events) > 7000:
        raise ValueError('Score exceeds 4095 notes, 65535 frames, or duration limit')
    visible = [sum(t <= f < t + d + LEAD for t, d, _ in events) for f in range(loop)]
    # Clearing 720*128 entries plus two cycles per painted row and scheduler.
    costs = [92160 + 10000 + 2 * sum(max(0, min(720, (f-t)*4) - max(0, (f-t-d)*4))
             for t, d, _ in events if t <= f < t+d+180) for f in range(loop)]
    if max(costs) >= 175000:
        raise ValueError('Score exceeds the vertical blanking bitmap rebuild budget')
    if max(visible) > SLOTS:
        raise ValueError(f'Score needs {max(visible)} slots, limit is {SLOTS}')
    (ROOT / 'sim').mkdir(exist_ok=True)
    (ROOT / 'src/score_config.vh').write_text(
        f'// Generated by tools/generate_waterfall.py\n'
        f'`define SCORE_COUNT {len(events)}\n`define SCORE_LOOP_FRAMES {loop}\n'
        f'`define SCORE_ADDR_WIDTH {len(events).bit_length()}\n', encoding='ascii')
    addr_width = len(events).bit_length()
    depth = 1 << addr_width
    lines = ['// Generated synchronous score ROM; one entry per note.',
             '`timescale 1ns/1ps',
             f'module piano_score_rom(input wire clk, input wire [{addr_width-1}:0] address,',
             '    output reg [63:0] data);',
             f'    reg [63:0] contents [0:{depth-1}];',
             '    initial begin']
    for i in range(depth):
        word = 0xffff000000000000
        if i < len(events):
            start, duration, note = events[i]
            key = keys[note]
            half = 5 if key['black'] else 10
            left, right = key['center'] - half, key['center'] + half
            word = ((start << 48) | (duration << 32) | (note << 25)
                    | (left << 14) | (right << 3) | ((note >= 39) << 2))
        lines.append(f"        contents[{i}] = 64'h{word:016x};")
    lines += ['    end', '    always @(posedge clk) data <= contents[address];', 'endmodule', '']
    (ROOT / 'src/piano_score_rom.v').write_text('\n'.join(lines), encoding='ascii')
    # Per-column lookup removes division/modulo from the 108 MHz pixel path.
    lines = ['// Generated keyboard geometry: 52 white keys and 36 black keys.',
             '`timescale 1ns/1ps',
             'module piano_keymap(input wire clk, input wire [10:0] x,',
             '    output reg [23:0] column);',
             '    always @(posedge clk) begin', '        case (x)']
    columns = []
    for x in range(1600):
        white = next((k for k in keys if not k['black'] and k['left'] <= x < k['right']), None)
        black = next((k for k in keys if k['black'] and k['left'] <= x < k['right']), None)
        wi, bi = (white['note'] if white else 127), (black['note'] if black else 127)
        edge = bool(white and x >= white['right'] - 2)
        marker = bool(white and white['midi'] % 12 == 0 and abs(x - white['center']) < 3)
        word = wi | (bi << 7) | (edge << 14) | (marker << 15)
        lane = next((k for k in keys if k['center']-(5 if k['black'] else 10) <= x
                     < k['center']+(5 if k['black'] else 10)), None)
        lane_note = lane['note'] if lane else 127
        half = (5 if lane['black'] else 10) if lane else 0
        inside = bool(lane and lane['center']-half+2 <= x < lane['center']+half-2)
        word |= (lane_note << 16) | (inside << 23)
        columns.append(word)
        lines.append(f"            11'd{x}: column <= 24'h{word:06x};")
    lines += ["            default: column <= 24'h7f3fff;", '        endcase', '    end', 'endmodule', '']
    (ROOT / 'src/piano_keymap.v').write_text('\n'.join(lines), encoding='ascii')
    expected = []
    for frame in range(loop):
        mask = 0
        for t, d, note in events:
            if t + LEAD <= frame < t + d + LEAD:
                mask |= 1 << note
        expected.append(f'{mask:022x}')
    (ROOT / 'sim/expected_keys.hex').write_text('\n'.join(expected) + '\n', encoding='ascii')
    (ROOT / 'sim/expected_count.hex').write_text('\n'.join(f'{c:02x}' for c in visible) + '\n', encoding='ascii')
    (ROOT / 'sim/key_centers.hex').write_text(
        '\n'.join(f"{((k['black'] << 11) | k['center']):03x}" for k in keys) + '\n', encoding='ascii')
    data = dict(source=str(args.midi) if args.midi else 'built-in 88-key exercise',
                width=1600, height=900, key_y=KEY_Y, lead=LEAD, speed=SPEED,
                loop_frames=loop, peak_slots=max(visible), keys=keys, events=events,
                columns=columns)
    (ROOT / 'sim/waterfall_reference.json').write_text(json.dumps(data, indent=2), encoding='utf-8')
    print(f'{len(events)} notes, {loop / 60:.2f}s loop, peak {max(visible)}/{SLOTS} slots')


if __name__ == '__main__':
    main()
