"""Generate the fixed RGB565 ROM and a preview of the actual FPGA output."""
import argparse
from pathlib import Path

from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parents[1]
WIDTH, HEIGHT = 208, 240


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("image", type=Path)
    args = parser.parse_args()
    with Image.open(args.image) as source:
        source = ImageOps.exif_transpose(source).convert("RGB")
        thumbnail = ImageOps.contain(source, (WIDTH, HEIGHT), Image.Resampling.LANCZOS)
        canvas = Image.new("RGB", (WIDTH, HEIGHT))
        canvas.paste(thumbnail, ((WIDTH - thumbnail.width) // 2,
                                (HEIGHT - thumbnail.height) // 2))

    words = []
    decoded = []
    pixels = canvas.get_flattened_data() if hasattr(canvas, "get_flattened_data") else canvas.getdata()
    for r, g, b in pixels:
        r5, g6, b5 = r >> 3, g >> 2, b >> 3
        words.append((r5 << 11) | (g6 << 5) | b5)
        decoded.append(((r5 << 3) | (r5 >> 2), (g6 << 2) | (g6 >> 4),
                        (b5 << 3) | (b5 >> 2)))
    rom = ROOT / "src" / "photo_rgb565.hex"
    rom.write_text("".join(f"{word:04x}\n" for word in words), encoding="ascii")
    # The generated case is independent of the IDE's working directory.
    rtl = [
        "// Generated by tools/prepare_image.py. One-cycle synchronous RGB565 ROM.",
        "`timescale 1ns/1ps",
        "module photo_rom(input wire clk, input wire [15:0] address,",
        "                 output reg [15:0] pixel);",
        "`ifdef PHOTO_ROM_SIM",
        "    reg [15:0] memory [0:49919];",
        "    initial $readmemh(\"src/photo_rgb565.hex\", memory);",
        "    always @(posedge clk) begin",
        "        if (address < 16'd49920) pixel <= memory[address];",
        "        else pixel <= 16'h0000;",
        "    end",
        "`else",
        "    always @(posedge clk) begin",
        "        case (address)",
    ]
    rtl.extend(f"            16'd{i}: pixel <= 16'h{word:04x};"
               for i, word in enumerate(words))
    rtl.extend(["            default: pixel <= 16'h0000;", "        endcase",
                "    end", "`endif", "endmodule", ""])
    (ROOT / "src" / "photo_rom.v").write_text("\n".join(rtl), encoding="ascii")
    quantized = Image.new("RGB", (WIDTH, HEIGHT))
    quantized.putdata(decoded)
    preview = Image.new("RGB", (640, 480))
    preview.paste(quantized.resize((416, 480), Image.Resampling.NEAREST), (112, 0))
    preview.save(ROOT / "preview.png")
    print(f"{len(words)} RGB565 pixels, {len(words)*16} bits; preview.png")


if __name__ == "__main__":
    main()
